import Foundation

/// The app's languages. A person can pick one, or follow the Mac.
public enum Language: String, CaseIterable, Sendable {
    case system, english, spanish

    public static let settingsKey = "language"

    /// A language for the work inside `Language.$override.withValue`, and only that work: drawing a view in
    /// one language never changes the language of anything running beside it.
    @TaskLocal public static var override: Language?

    public static var current: Language {
        override ?? Language(rawValue: UserDefaults.standard.string(forKey: settingsKey) ?? "") ?? .system
    }

    /// The language in effect once "system" is resolved.
    public var resolved: Language {
        guard self == .system else { return self }
        return Self.mac
    }

    /// The Mac's language, read once: every piece of text on screen asks for it, and reading the
    /// system's list each time made each lookup cost as much as drawing a row.
    private static let mac: Language = Locale.preferredLanguages.first?.hasPrefix("es") == true ? .spanish : .english

    public var locale: Locale {
        Locale(identifier: resolved == .spanish ? "es_CL" : "en_US")
    }
}

/// Text on screen, written in English and looked up in the table below. This needs no Xcode, and
/// adding a language means adding one table.
public func T(_ english: String) -> String { translate(english, to: Language.current) }

public func translate(_ english: String, to language: Language) -> String {
    language.resolved == .spanish ? (spanish[english] ?? english) : english
}

